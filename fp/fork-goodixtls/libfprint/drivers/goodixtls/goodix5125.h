// Per-chip constants verified empirically on the live 5125:
//   - psk_flags 0xbb020003 (same family as the 511/5F10)
//   - reset_number 2048 (same as 511; 5F10 reports 1024)
//   - firmware "GF_ST411SEC_APP_12509"
//   - ENABLE_CHIP body "01 02" (like 5F10, NOT the generic "01 00")
//   - config blob: 256 bytes (captured from the chip's own UPLOAD_CONFIG_MCU reply)
//   - geometry: 64 px scan width x 80 scanlines, scan_width=88 (same as 511)
//   - FDT mode: 14 bytes {0x09,0x01,0xb3,0xb3,0xc3,0xc3,0xa8,0xa8,0xb5,0xb5,0xa8,0xa8,0xb7,0xb7}
//   - Sensor streams decoded row-major as 88 scanlines x 64 px, presented
//     STRAIGHT (no transpose) with ridges inverted dark (same as 511)
//   - Per-device TLS session PSK (32 bytes) loaded from disk at activation,
//     like 5F10. NOT compiled in.

